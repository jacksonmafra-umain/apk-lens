def _write_evidence(result: AnalysisResult, root: Path) -> list[Path]:
    directory = root / "evidence"
    directory.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    def write(name: str, text: str) -> None:
        path = directory / name
        path.write_text(text)
        written.append(path)

    findings = result.network.get("findings", [])
    hosts = sorted({host for finding in findings for host in finding.get("hosts", [])})
    write("hosts.txt", "\n".join(hosts) + "\n" if hosts else "")

    write(
        "domains.csv",
        "domain,bucket,host_count,operator,purpose\n"
        + "".join(
            f"{finding.get('domain')},{finding.get('bucket')},"
            f"{len(finding.get('hosts', []))},"
            f"\"{finding.get('operator') or ''}\",{finding.get('purpose') or ''}\n"
            for finding in findings
        ),
    )

    sample_urls = sorted({url for finding in findings for url in finding.get("sample_urls", [])})
    write("urls-sample.txt", "\n".join(sample_urls) + "\n" if sample_urls else "")

    cleartext = result.network.get("cleartext_urls", [])
    write("cleartext-urls.txt", "\n".join(cleartext) + "\n" if cleartext else "")

    write(
        "permissions.csv",
        "permission,verdict,tier\n"
        + "".join(
            f"{finding['name']},{finding['verdict']},{finding['tier']}\n"
            for finding in result.permissions.get("findings", [])
        ),
    )

    write(
        "sinks.tsv",
        "api\tcategory\tmatches\torigins\tcitations\n"
        + "".join(
            "\t".join(
                [
                    finding.get("sink_id", ""),
                    finding.get("category_label", ""),
                    str(finding.get("total_hits", 0)),
                    ";".join(f"{k}={v}" for k, v in (finding.get("origin_counts") or {}).items()),
                    ";".join(finding.get("citations", [])),
                ]
            )
            + "\n"
            for finding in result.sinks.get("present", [])
        ),
    )

    write(
        "native-libraries.csv",
        "library,abi,size_bytes,identified_as,markers\n"
        + "".join(
            f"{lib.get('name')},{lib.get('abi')},{lib.get('size_bytes')},"
            f"\"{lib.get('identified_as') or ''}\","
            f"\"{';'.join(sorted({m['name'] for m in lib.get('markers', [])}))}\"\n"
            for lib in result.native.get("libraries", [])
        ),
    )

    decoded = result.native.get("decoded_assets", [])
    if decoded:
        blocks = [
            f"## {Path(item['source']).name}\n\n"
            f"- transform: `{item['transform']}`\n"
            f"- key: `{item.get('key') or 'n/a'}`\n"
            f"- reproduce:\n\n```sh\n{item['reproduce']}\n```\n\n"
            f"```\n{item['preview']}\n```\n"
            for item in decoded
        ]
        write("decoded-assets.md", "# Decoded assets\n\n" + "\n".join(blocks))

    return written


# -------------------------------------------------------------------- write


def write(result: AnalysisResult, out_dir: Path | None = None) -> ReportSet:
    """Render the full report set for ``result`` and return what was written."""
    root = (out_dir or DEFAULT_OUT_DIR) / result.slug
    root.mkdir(parents=True, exist_ok=True)
    produced = ReportSet(root=root)

    for name, builder in DOCUMENTS:
        content = builder(result)
        if LIMITS_MARKER not in content:
            raise ApkLensError(
                f"report {name} was rendered without its limits section",
                hint=(
                    "every document must state what it does not prove; add a "
                    f"'{LIMITS_MARKER}' block to its builder"
                ),
            )
        path = root / name
        path.write_text(content)
        produced.documents.append(path)

    produced.evidence = _write_evidence(result, root)

    results_path = root / "results.json"
    results_path.write_text(json.dumps(result.to_dict(), indent=2) + "\n")
    produced.results_json = results_path

    return produced
